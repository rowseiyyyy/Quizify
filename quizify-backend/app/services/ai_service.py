def generate_quiz(text: str, subject: str, question_count: int, difficulty: str,
                   question_types: List[str]) -> List[Dict]:
    import logging
    if settings.GEMINI_API_KEY:
        try:
            questions = _generate_quiz_gemini(text, subject, question_count, difficulty, question_types)
            if questions:
                if len(questions) < question_count:
                    logging.warning(
                        "Gemini returned only %d/%d valid questions; padding from offline generator",
                        len(questions), question_count,
                    )
                    existing = {q["question_text"].lower() for q in questions}
                    for q in _generate_quiz_offline(text, subject, question_count * 2, difficulty, question_types):
                        if len(questions) >= question_count:
                            break
                        if q["question_text"].lower() not in existing:
                            questions.append(q)
                            existing.add(q["question_text"].lower())
                return questions
            logging.warning("Gemini returned no valid questions; using offline generator")
        except Exception as e:
            logging.exception("Gemini quiz generation failed, falling back to offline generator")
    return _generate_quiz_offline(text, subject, question_count, difficulty, question_types)

def generate_flashcards(text: str, subject: str, count: int) -> List[Dict]:
    import logging
    if settings.GEMINI_API_KEY:
        try:
            flashcards = _generate_flashcards_gemini(text, subject, count)
            if flashcards:
                if len(flashcards) < count:
                    logging.warning(
                        "Gemini returned only %d/%d valid flashcards; padding from offline generator",
                        len(flashcards), count,
                    )
                    existing = {fc["front"].lower() for fc in flashcards}
                    for fc in _generate_flashcards_offline(text, subject, count * 2):
                        if len(flashcards) >= count:
                            break
                        if fc["front"].lower() not in existing:
                            flashcards.append(fc)
                            existing.add(fc["front"].lower())
                return flashcards
            logging.warning("Gemini returned no valid flashcards; using offline generator")
        except Exception as e:
            logging.exception("Gemini flashcard generation failed, falling back to offline generator")
    return _generate_flashcards_offline(text, subject, count)

