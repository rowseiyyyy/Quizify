"""AI generation layer.

If `GEMINI_API_KEY` is configured (Google AI Studio), quizzes/flashcards are
generated by calling the Gemini API's OpenAI-compatible Chat Completions
endpoint with a strict JSON-output prompt.

If no key is configured, a deterministic, fully-offline heuristic generator
is used instead so the whole product still works end-to-end (useful for
local dev, demos, and grading environments without external API access).
"""
import json
import random
import re
from typing import List, Dict

import httpx

from app.config import settings
from app.services.pdf_service import split_into_sentences, identify_key_terms

random.seed()


